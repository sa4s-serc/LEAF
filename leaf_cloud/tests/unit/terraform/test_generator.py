    @patch('os.makedirs')
    @patch('builtins.open', new_callable=mock_open)
    def test_write_terraform_files(self, mock_file, mock_makedirs):
        """Test writing Terraform configuration to files."""
        generator = TerraformGenerator(SAMPLE_SIMULATION_RESULTS)
        test_dir = "/test/dir"
        
        # Call the method
        generator.write_terraform_files(test_dir)
        
        # Verify directory creation
        mock_makedirs.assert_called_once_with(test_dir, exist_ok=True)
        
        # Verify files were written
        assert mock_file.call_count >= 2  # At least main.tf and variables.tf
        
        # Check if main.tf was written
        main_tf_call = None
        for call in mock_file.call_args_list:
            if str(call[0][0]).endswith('main.tf'):
                main_tf_call = call
                break
                
        assert main_tf_call is not None, "main.tf was not written"
        assert 'w' in main_tf_call[0][1], "File not opened in write mode"

