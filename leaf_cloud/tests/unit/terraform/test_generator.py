    def test_write_terraform_files_handles_io_errors(self):
        """Test that IO errors during file writing are handled gracefully."""
        generator = TerraformGenerator(SAMPLE_SIMULATION_RESULTS)
        
        # Create a context manager that raises IOError for all file operations
        def mock_open_raises(*args, **kwargs):
            if 'w' in args[1]:  # Only raise on write mode
                raise IOError("Test IO Error")
            return MagicMock()
        
        with patch('builtins.open', side_effect=mock_open_raises), \
             patch('os.makedirs') as mock_makedirs, \
             patch('json.dump') as mock_json_dump:
            
            # Should not raise an exception
            generator.write_terraform_files("/test/dir")
            
            # Verify that makedirs was called
            mock_makedirs.assert_called_once_with("/test/dir", exist_ok=True)
            
            # Verify that json.dump was not called since all file operations should fail
            assert not mock_json_dump.called, "json.dump should not be called when file operations fail"
            
