    def test_compare_configs_with_nested_structures(self):
        """Test comparison of nested configurations."""
        generator = TerraformGenerator(SAMPLE_SIMULATION_RESULTS)
        
        original = {
            "nested": {
                "key1": "value1",
                "key2": "value2"
            },
            "list": [1, 2, 3]
        }
        
        optimized = {
            "nested": {
                "key1": "value1_modified",
                "key3": "new_value"
            },
            "list": [1, 4, 3]
        }
        
        changes = generator._compare_configs(original, optimized)
        
        # Check nested dictionary changes
        assert "nested.key1" in changes
        assert changes["nested.key1"]["before"] == "value1"
        assert changes["nested.key1"]["after"] == "value1_modified"
        
        # Check removed key
        assert "nested.key2" in changes
        assert changes["nested.key2"]["before"] == "value2"
        assert changes["nested.key2"]["after"] is None
        
        # Check added key
        assert "nested.key3" in changes
        assert changes["nested.key3"]["before"] is None
        assert changes["nested.key3"]["after"] == "new_value"
        
        # Check list changes (should be compared as a whole, not by index)
        assert "list" in changes
        assert changes["list"]["before"] == [1, 2, 3]
        assert changes["list"]["after"] == [1, 4, 3]
        
