    def test_generate_resource_block(self):
        """Test generation of a single resource block."""
        generator = TerraformGenerator(SAMPLE_SIMULATION_RESULTS)
        resource_type = "google_compute_instance"
        resource_name = "test_instance"
        resource_config = {
            "machine_type": "e2-micro",
            "zone": "us-central1-a"
        }
        
        block = generator.generate_resource_block(
            resource_type, resource_name, resource_config
        )
        
        assert block.startswith(f'resource "{resource_type}" "{resource_name}"')
        assert "machine_type = " in block
        assert "zone = " in block
        assert block.endswith("}\n")

